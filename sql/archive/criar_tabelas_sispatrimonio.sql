-- Script de criação das tabelas do Sistema de Inventário
-- Banco de dados: sispatrimonio
-- Data: 2024

-- =====================================================
-- TABELAS BASE (sem dependências)
-- =====================================================

-- Tabela de Setores
CREATE TABLE IF NOT EXISTS TABELA_SETOR (
    ID SERIAL PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela de Responsáveis
CREATE TABLE IF NOT EXISTS TABELA_RESPONSAVEL (
    ID SERIAL PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    MATRICULA VARCHAR(20) UNIQUE,
    EMAIL VARCHAR(100),
    TELEFONE VARCHAR(20),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela de Salas
CREATE TABLE IF NOT EXISTS TABELA_SALA (
    ID_SALA SERIAL PRIMARY KEY,
    DESCRICAO VARCHAR(200) NOT NULL,
    ANDAR VARCHAR(10),
    BLOCO VARCHAR(10),
    CAPACIDADE INTEGER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela de Coletores
CREATE TABLE IF NOT EXISTS TABELA_COLETOR (
    ID SERIAL PRIMARY KEY,
    NOME_COLETOR VARCHAR(150) NOT NULL,
    MATRICULA VARCHAR(20) UNIQUE,
    EMAIL VARCHAR(100),
    TELEFONE VARCHAR(20),
    ATIVO CHAR(1) DEFAULT 'S' CHECK (ATIVO IN ('S', 'N')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- =====================================================
-- TABELAS COM DEPENDÊNCIAS
-- =====================================================

-- Tabela de Usuários
CREATE TABLE IF NOT EXISTS TABELA_USUARIO (
    ID SERIAL PRIMARY KEY,
    LOGIN VARCHAR(50) NOT NULL UNIQUE,
    SENHA_HASH VARCHAR(255) NOT NULL,
    NOME_COMPLETO VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    MATRICULA VARCHAR(20) UNIQUE,
    PERFIL VARCHAR(20) NOT NULL CHECK (PERFIL IN ('ADMIN', 'SUPERVISOR', 'COLETOR', 'CONSULTA')),
    ID_SETOR INTEGER REFERENCES TABELA_SETOR(ID),
    ATIVO CHAR(1) DEFAULT 'S' CHECK (ATIVO IN ('S', 'N')),
    DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_ULTIMO_ACESSO TIMESTAMP,
    TENTATIVAS_LOGIN INTEGER DEFAULT 0,
    BLOQUEADO CHAR(1) DEFAULT 'N' CHECK (BLOQUEADO IN ('S', 'N')),
    DATA_BLOQUEIO TIMESTAMP,
    DATA_EXPIRACAO_SENHA TIMESTAMP DEFAULT (CURRENT_TIMESTAMP + INTERVAL '90 days'),
    PRIMEIRO_ACESSO CHAR(1) DEFAULT 'S' CHECK (PRIMEIRO_ACESSO IN ('S', 'N')),
    OBSERVACOES TEXT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela de Patrimônio
CREATE TABLE IF NOT EXISTS TABELA_PATRIMONIO (
    ID SERIAL PRIMARY KEY,
    NUMERO VARCHAR(20) NOT NULL UNIQUE,
    STATUS VARCHAR(20) DEFAULT 'ATIVO' CHECK (STATUS IN ('ATIVO', 'INATIVO', 'BAIXADO', 'MANUTENCAO')),
    DESCRICAO TEXT NOT NULL,
    ROTULOS TEXT,
    ID_RESPONSAVEL INTEGER REFERENCES TABELA_RESPONSAVEL(ID),
    VALOR_AQUISICAO DECIMAL(15,2) CHECK (VALOR_AQUISICAO > 0),
    VALOR_DEPRECIADO DECIMAL(15,2),
    NUMERO_NOTA_FISCAL VARCHAR(50),
    NUMERO_SERIE VARCHAR(100),
    DATA_ENTRADA DATE NOT NULL,
    DATA_CARGA TIMESTAMP,
    FORNECEDOR VARCHAR(200),
    ID_SALA INTEGER REFERENCES TABELA_SALA(ID_SALA),
    ESTADO_CONSERVACAO VARCHAR(20) CHECK (ESTADO_CONSERVACAO IN ('OTIMO', 'BOM', 'REGULAR', 'RUIM', 'PESSIMO')),
    MARCA VARCHAR(100),
    MODELO VARCHAR(100),
    CATEGORIA VARCHAR(100),
    ED VARCHAR(100),
    OBSERVACOES TEXT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela de Inventário
CREATE TABLE IF NOT EXISTS TABELA_INVENTARIO (
    ID SERIAL PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    ANO INTEGER NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE,
    OBSERVACAO TEXT,
    STATUS VARCHAR(20) DEFAULT 'PLANEJADO' CHECK (STATUS IN ('PLANEJADO', 'EM_ANDAMENTO', 'CONCLUIDO', 'CANCELADO')),
    ID_RESPONSAVEL INTEGER REFERENCES TABELA_RESPONSAVEL(ID),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_data_inventario CHECK (DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO)
);

-- Tabela de Coleta (relaciona inventário com patrimônio)
CREATE TABLE IF NOT EXISTS TABELA_COLETA (
    ID SERIAL PRIMARY KEY,
    ID_INVENTARIO INTEGER NOT NULL REFERENCES TABELA_INVENTARIO(ID),
    ID_PATRIMONIO INTEGER NOT NULL REFERENCES TABELA_PATRIMONIO(ID),
    ID_COLETOR INTEGER NOT NULL REFERENCES TABELA_COLETOR(ID),
    DATA_COLETA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS_ENCONTRADO CHAR(1) DEFAULT 'S' CHECK (STATUS_ENCONTRADO IN ('S', 'N')),
    LOCALIZACAO_ATUAL VARCHAR(200),
    ESTADO_CONSERVACAO_ATUAL VARCHAR(20) CHECK (ESTADO_CONSERVACAO_ATUAL IN ('OTIMO', 'BOM', 'REGULAR', 'RUIM', 'PESSIMO')),
    OBSERVACOES_COLETA TEXT,
    LATITUDE DECIMAL(10,8),
    LONGITUDE DECIMAL(11,8),
    FOTO_PATH VARCHAR(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(ID_INVENTARIO, ID_PATRIMONIO)
);

-- =====================================================
-- ÍNDICES PARA PERFORMANCE
-- =====================================================

