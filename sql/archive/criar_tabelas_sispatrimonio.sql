-- =====================================================
-- TRIGGERS PARA AUDITORIA
-- =====================================================

-- Função para atualizar o campo updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ language 'plpgsql';

-- Triggers para atualizar updated_at automaticamente
CREATE TRIGGER update_setor_updated_at BEFORE UPDATE ON TABELA_SETOR FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER update_responsavel_updated_at BEFORE UPDATE ON TABELA_RESPONSAVEL FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER update_sala_updated_at BEFORE UPDATE ON TABELA_SALA FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER update_coletor_updated_at BEFORE UPDATE ON TABELA_COLETOR FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER update_usuario_updated_at BEFORE UPDATE ON TABELA_USUARIO FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER update_patrimonio_updated_at BEFORE UPDATE ON TABELA_PATRIMONIO FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER update_inventario_updated_at BEFORE UPDATE ON TABELA_INVENTARIO FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER update_coleta_updated_at BEFORE UPDATE ON TABELA_COLETA FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

