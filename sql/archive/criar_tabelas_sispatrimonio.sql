-- VIEWS ÚTEIS
-- =====================================================

-- View para patrimônios com informações completas
CREATE OR REPLACE VIEW vw_patrimonio_completo AS
SELECT 
    p.ID,
    p.NUMERO,
    p.STATUS,
    p.DESCRICAO,
    p.VALOR_AQUISICAO,
    p.VALOR_DEPRECIADO,
    p.DATA_ENTRADA,
    p.ESTADO_CONSERVACAO,
    r.NOME as RESPONSAVEL_NOME,
    s.DESCRICAO as SALA_DESCRICAO,
    p.OBSERVACOES
FROM TABELA_PATRIMONIO p
LEFT JOIN TABELA_RESPONSAVEL r ON p.ID_RESPONSAVEL = r.ID
LEFT JOIN TABELA_SALA s ON p.ID_SALA = s.ID_SALA;

-- View para usuários ativos
CREATE OR REPLACE VIEW vw_usuarios_ativos AS
SELECT 
    u.ID,
    u.LOGIN,
    u.NOME_COMPLETO,
    u.EMAIL,
    u.PERFIL,
    s.NOME as SETOR_NOME,
    u.DATA_ULTIMO_ACESSO
FROM TABELA_USUARIO u
LEFT JOIN TABELA_SETOR s ON u.ID_SETOR = s.ID
WHERE u.ATIVO = 'S' AND u.BLOQUEADO = 'N';

