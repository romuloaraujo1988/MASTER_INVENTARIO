CREATE INDEX IF NOT EXISTS idx_patrimonio_sala ON TABELA_PATRIMONIO(ID_SALA);
CREATE INDEX IF NOT EXISTS idx_patrimonio_data_entrada ON TABELA_PATRIMONIO(DATA_ENTRADA);

