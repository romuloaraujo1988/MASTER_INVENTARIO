    public static void main(String[] args) {
        boolean dryRun = true;
        for (String arg : args) {
            if ("--executar".equals(arg)) {
                dryRun = false;
            }
        }
        
        // Carregar driver PostgreSQL
        try {
            Class.forName("org.postgresql.Driver");
        } catch (ClassNotFoundException e) {
            System.err.println("Driver PostgreSQL nao encontrado!");
            return;
        }
        
        String url = String.format("jdbc:postgresql://%s:%s/%s", DB_HOST, DB_PORT, DB_NAME);
        
        System.out.println("Conectando ao servidor " + DB_HOST + "...");
        
        try (Connection conn = DriverManager.getConnection(url, DB_USER, DB_PASS)) {
            System.out.println("Conectado!");
            
            // Verificar quantos existem
            StringBuilder placeholders = new StringBuilder();
            for (int i = 0; i < PATRIMONIOS.length; i++) {
                if (i > 0) placeholders.append(",");
                placeholders.append("?");
            }
            
            String selectSql = "SELECT numero FROM tabela_patrimonio WHERE numero IN (" + placeholders + ")";
            Set<String> existentes = new HashSet<>();
            
            try (PreparedStatement ps = conn.prepareStatement(selectSql)) {
                for (int i = 0; i < PATRIMONIOS.length; i++) {
                    ps.setString(i + 1, PATRIMONIOS[i]);
                }
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        existentes.add(rs.getString(1));
                    }
                }
            }
            
            Set<String> naoEncontrados = new HashSet<>(Arrays.asList(PATRIMONIOS));
            naoEncontrados.removeAll(existentes);
            
            System.out.println("\n=== RESUMO ===");
            System.out.println("Patrimonios na lista: " + PATRIMONIOS.length);
            System.out.println("Encontrados no banco: " + existentes.size());
            System.out.println("Nao encontrados: " + naoEncontrados.size());
            
            if (!naoEncontrados.isEmpty() && naoEncontrados.size() <= 30) {
                System.out.println("\nNao encontrados: " + naoEncontrados);
            }
            
            if (dryRun) {
                System.out.println("\n[DRY RUN] Nenhuma alteracao foi feita.");
                System.out.println("Execute com --executar para aplicar as alteracoes.");
            } else {
                // Executar UPDATE
                StringBuilder updatePlaceholders = new StringBuilder();
                List<String> listaExistentes = new ArrayList<>(existentes);
                for (int i = 0; i < listaExistentes.size(); i++) {
                    if (i > 0) updatePlaceholders.append(",");
                    updatePlaceholders.append("?");
                }
                
                String updateSql = "UPDATE tabela_patrimonio " +
                    "SET estado_conservacao = 'IRRECUPERAVEL', " +
                    "id_sala = ?, " +
                    "observacoes = COALESCE(observacoes || ' | ', '') || 'Para desfazimento - Leilao SV' " +
                    "WHERE numero IN (" + updatePlaceholders + ")";
                
                try (PreparedStatement ps = conn.prepareStatement(updateSql)) {
                    ps.setInt(1, ID_SALA_DESFAZIMENTO);
                    for (int i = 0; i < listaExistentes.size(); i++) {
                        ps.setString(i + 2, listaExistentes.get(i));
                    }
                    int rowsUpdated = ps.executeUpdate();
                    
                    System.out.println("\n=== SUCESSO ===");
                    System.out.println(rowsUpdated + " patrimonios atualizados!");
                    System.out.println("  - estado_conservacao: IRRECUPERAVEL");
                    System.out.println("  - id_sala: " + ID_SALA_DESFAZIMENTO + " (Sala do Desfazimento)");
                    System.out.println("  - observacoes: + 'Para desfazimento - Leilao SV'");
                }
            }
            
        } catch (SQLException e) {
            System.err.println("Erro: " + e.getMessage());
        }
    }
